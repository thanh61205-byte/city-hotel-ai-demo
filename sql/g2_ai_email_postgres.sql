-- G2 AI email store on PostgreSQL: schema g2_ai_v1 (docs/SPEC_AI_N8N_VI.md §6.1, §7.1).
--
-- Separate from the G2 action-log schemas (state schema 9): drafts, approvals and DEMO send jobs
-- never write action_plan / interventions / guest_responses. Every name is schema-qualified, so
-- nothing depends on a session search_path (works through a transaction pooler too).
--
-- Apply once as the schema OWNER (bootstrap), idempotent:
--   python -m dashboard.ai_email.bootstrap --apply-schema      (reads G2_AI_OWNER_DB_URL)
-- Roles and grants for the Streamlit runtime and n8n: sql/g2_ai_email_roles_postgres.sql.
--
-- Concurrency: n8n calls one function per step; each call is one transaction. Lock order is
-- always approval row -> send job row, so revocation and dispatch serialise without deadlock.
-- No network call ever happens inside these transactions.
CREATE SCHEMA IF NOT EXISTS g2_ai_v1;

CREATE TABLE IF NOT EXISTS g2_ai_v1.meta (
  key   text PRIMARY KEY,
  value text NOT NULL
);
INSERT INTO g2_ai_v1.meta (key, value) VALUES ('ai_schema_version', '1') ON CONFLICT (key) DO NOTHING;

CREATE TABLE IF NOT EXISTS g2_ai_v1.workspaces (
  workspace_id   text PRIMARY KEY CHECK (workspace_id ~ '^[a-z0-9][a-z0-9_-]{0,62}$'),
  source_run_id  text NOT NULL,
  policy_version text NOT NULL,
  business_as_of date NOT NULL,
  created_at     timestamptz NOT NULL DEFAULT now()
);

-- Server-side allowlist of the team's test inboxes. Written by the bootstrap (owner) only.
CREATE TABLE IF NOT EXISTS g2_ai_v1.test_recipients (
  recipient_id text PRIMARY KEY CHECK (recipient_id ~ '^[a-z0-9][a-z0-9_-]{0,62}$' AND recipient_id <> 'mock-preview'),
  address      text NOT NULL UNIQUE CHECK (address = lower(address) AND address ~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'),
  active       boolean NOT NULL DEFAULT true,
  note         text,
  created_at   timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS g2_ai_v1.generation_requests (
  request_id        uuid PRIMARY KEY,
  workspace_id      text NOT NULL REFERENCES g2_ai_v1.workspaces (workspace_id),
  demo_session_id   text,
  email_type        text NOT NULL CHECK (email_type IN ('reminder','booking_confirmation','guest_reply')),
  booking_id        bigint,
  language          text NOT NULL CHECK (language IN ('en','vi')),
  context_json      jsonb NOT NULL,
  context_hash      text NOT NULL CHECK (length(context_hash) = 64),
  engine            text NOT NULL CHECK (engine IN ('n8n','local')),
  requested_mode    text NOT NULL CHECK (requested_mode IN ('live_ai','fixture','manual')),
  status            text NOT NULL DEFAULT 'queued' CHECK (status IN ('queued','processing','succeeded','failed')),
  lease_token       uuid,
  lease_expires_at  timestamptz,
  attempts          integer NOT NULL DEFAULT 0,
  result_json       jsonb,
  validation_errors jsonb,
  analysis_mode     text CHECK (analysis_mode IN ('live_ai','fixture','manual')),
  model             text,
  prompt_version    text,
  token_usage       jsonb,
  error             text,
  requested_by      text,
  created_at        timestamptz NOT NULL DEFAULT now(),
  claimed_at        timestamptz,
  completed_at      timestamptz,
  UNIQUE (request_id, workspace_id),
  CONSTRAINT request_type_matches_context CHECK (context_json->>'email_type' = email_type),
  -- Only a reply carries a guest message; a reminder / confirmation never does.
  CONSTRAINT guest_message_only_for_reply CHECK (
    (email_type = 'guest_reply') = COALESCE(jsonb_typeof(context_json->'guest_message') = 'object', false)),
  CONSTRAINT succeeded_has_result CHECK (status <> 'succeeded' OR (result_json IS NOT NULL AND analysis_mode IS NOT NULL)),
  CONSTRAINT lease_only_while_processing CHECK ((status = 'processing') = (lease_token IS NOT NULL))
);

-- Immutable revisions: the exact email (DEMO prefix / footer included) and its hash.
CREATE TABLE IF NOT EXISTS g2_ai_v1.draft_revisions (
  revision_id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id        text NOT NULL,
  request_id          uuid NOT NULL,
  revision_no         integer NOT NULL CHECK (revision_no >= 1),
  email_type          text NOT NULL,
  booking_id          bigint,
  language            text NOT NULL,
  context_hash        text NOT NULL,
  editable_subject    text NOT NULL,
  editable_body       text NOT NULL,
  rendered_subject    text NOT NULL CHECK (rendered_subject LIKE '[DEMO] %'),
  rendered_body       text NOT NULL,
  content_hash        text NOT NULL CHECK (length(content_hash) = 64),
  analysis_json       jsonb,
  analysis_mode       text NOT NULL CHECK (analysis_mode IN ('live_ai','fixture','manual')),
  missing_information jsonb NOT NULL DEFAULT '[]'::jsonb,
  send_blockers       jsonb NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(send_blockers) = 'array'),
  source              text NOT NULL CHECK (source IN ('generated','staff_edit')),
  created_by          text,
  demo_session_id     text,
  created_at          timestamptz NOT NULL DEFAULT now(),
  UNIQUE (request_id, revision_no),
  UNIQUE (revision_id, workspace_id),
  FOREIGN KEY (request_id, workspace_id) REFERENCES g2_ai_v1.generation_requests (request_id, workspace_id)
);

CREATE TABLE IF NOT EXISTS g2_ai_v1.approvals (
  approval_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id      text NOT NULL,
  revision_id       bigint NOT NULL,
  email_type        text NOT NULL,
  booking_id        bigint,
  context_hash      text NOT NULL,
  content_hash      text NOT NULL,
  recipient_id      text NOT NULL,
  recipient_address text NOT NULL,
  sender_ref        text NOT NULL CHECK (btrim(sender_ref) <> ''),
  delivery_mode     text NOT NULL CHECK (delivery_mode IN ('mock','team_test_email')),
  reviewer_label    text NOT NULL CHECK (btrim(reviewer_label) <> ''),
  approved_at       timestamptz NOT NULL DEFAULT now(),
  expires_at        timestamptz NOT NULL,
  revoked_at        timestamptz,
  revoked_by        text,
  revoke_reason     text,
  demo_session_id   text,
  UNIQUE (approval_id, workspace_id),
  FOREIGN KEY (revision_id, workspace_id) REFERENCES g2_ai_v1.draft_revisions (revision_id, workspace_id),
  CONSTRAINT revocation_complete CHECK ((revoked_at IS NULL) = (revoke_reason IS NULL)),
  CONSTRAINT mock_recipient CHECK ((delivery_mode = 'mock') = (recipient_id = 'mock-preview')),
  CONSTRAINT expires_after_approval CHECK (expires_at > approved_at)
);

CREATE TABLE IF NOT EXISTS g2_ai_v1.send_jobs (
  job_id              uuid PRIMARY KEY,
  workspace_id        text NOT NULL,
  approval_id         bigint NOT NULL,
  revision_id         bigint NOT NULL,
  send_key            text NOT NULL UNIQUE CHECK (length(send_key) = 64),
  delivery_mode       text NOT NULL CHECK (delivery_mode IN ('mock','team_test_email')),
  recipient_id        text NOT NULL,
  recipient_address   text NOT NULL,
  sender_ref          text NOT NULL,
  status              text NOT NULL DEFAULT 'queued' CHECK (status IN
                        ('queued','claimed','dispatching','simulated','provider_accepted','failed','unknown')),
  version             integer NOT NULL DEFAULT 1,
  lease_token         uuid,
  lease_expires_at    timestamptz,
  executor            text,
  provider_message_id text,
  detail              text,
  receipt_verified_by text,
  receipt_verified_at timestamptz,
  requested_by        text,
  demo_session_id     text,
  created_at          timestamptz NOT NULL DEFAULT now(),
  updated_at          timestamptz NOT NULL DEFAULT now(),
  dispatch_started_at timestamptz,
  finished_at         timestamptz,
  FOREIGN KEY (approval_id, workspace_id) REFERENCES g2_ai_v1.approvals (approval_id, workspace_id),
  FOREIGN KEY (revision_id, workspace_id) REFERENCES g2_ai_v1.draft_revisions (revision_id, workspace_id),
  CONSTRAINT lease_while_claimed CHECK ((status IN ('claimed','dispatching')) = (lease_token IS NOT NULL)),
  CONSTRAINT simulated_is_mock CHECK (status <> 'simulated' OR delivery_mode = 'mock'),
  CONSTRAINT accepted_is_real CHECK (status <> 'provider_accepted' OR delivery_mode = 'team_test_email')
);
CREATE INDEX IF NOT EXISTS ix_ai_jobs_approval ON g2_ai_v1.send_jobs (approval_id);
CREATE INDEX IF NOT EXISTS ix_ai_revisions_request ON g2_ai_v1.draft_revisions (request_id);
CREATE INDEX IF NOT EXISTS ix_ai_approvals_revision ON g2_ai_v1.approvals (revision_id);
CREATE INDEX IF NOT EXISTS ix_ai_requests_ws ON g2_ai_v1.generation_requests (workspace_id, created_at);

-- Append-only audit trail of every state change.
CREATE TABLE IF NOT EXISTS g2_ai_v1.events (
  event_id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id    text NOT NULL REFERENCES g2_ai_v1.workspaces (workspace_id),
  entity          text NOT NULL CHECK (entity IN ('request','revision','approval','job')),
  entity_id       text NOT NULL,
  kind            text NOT NULL,
  from_status     text,
  to_status       text,
  actor           text,
  detail          jsonb,
  demo_session_id text,
  at              timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX IF NOT EXISTS ix_ai_events_entity ON g2_ai_v1.events (entity, entity_id);

-- ------------------------------------------------------------------ guards (triggers)
CREATE OR REPLACE FUNCTION g2_ai_v1.content_hash(p_subject text, p_body text) RETURNS text
LANGUAGE sql IMMUTABLE AS $$
  SELECT encode(sha256(convert_to(p_subject || E'\n\x1f\n' || p_body, 'UTF8')), 'hex')
$$;

CREATE OR REPLACE FUNCTION g2_ai_v1.append_only() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = TG_TABLE_NAME || ' is append-only';
END $$;
CREATE OR REPLACE TRIGGER revisions_append_only BEFORE UPDATE OR DELETE ON g2_ai_v1.draft_revisions
  FOR EACH ROW EXECUTE FUNCTION g2_ai_v1.append_only();
CREATE OR REPLACE TRIGGER events_append_only BEFORE UPDATE OR DELETE ON g2_ai_v1.events
  FOR EACH ROW EXECUTE FUNCTION g2_ai_v1.append_only();
CREATE OR REPLACE TRIGGER approvals_no_delete BEFORE DELETE ON g2_ai_v1.approvals
  FOR EACH ROW EXECUTE FUNCTION g2_ai_v1.append_only();
CREATE OR REPLACE TRIGGER jobs_no_delete BEFORE DELETE ON g2_ai_v1.send_jobs
  FOR EACH ROW EXECUTE FUNCTION g2_ai_v1.append_only();

-- A revision matches its request (type, context) and its own content hash.
CREATE OR REPLACE FUNCTION g2_ai_v1.check_revision() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE r g2_ai_v1.generation_requests;
BEGIN
  SELECT * INTO r FROM g2_ai_v1.generation_requests WHERE request_id = NEW.request_id;
  IF r.status IS DISTINCT FROM 'succeeded' THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'A revision needs a succeeded generation request';
  END IF;
  IF NEW.email_type <> r.email_type OR NEW.context_hash <> r.context_hash OR NEW.language <> r.language
     OR NEW.booking_id IS DISTINCT FROM r.booking_id THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'Revision does not match its request (type, context, booking)';
  END IF;
  IF NEW.content_hash <> g2_ai_v1.content_hash(NEW.rendered_subject, NEW.rendered_body) THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'Revision content hash does not match its text';
  END IF;
  RETURN NEW;
END $$;
CREATE OR REPLACE TRIGGER check_revision BEFORE INSERT ON g2_ai_v1.draft_revisions
  FOR EACH ROW EXECUTE FUNCTION g2_ai_v1.check_revision();

-- NULL when the approval may still send this job's email, else the reason.
CREATE OR REPLACE FUNCTION g2_ai_v1.approval_problem(p_approval_id bigint, p_job_id uuid) RETURNS text
LANGUAGE plpgsql STABLE AS $$
DECLARE a g2_ai_v1.approvals; r g2_ai_v1.draft_revisions; j g2_ai_v1.send_jobs; rc g2_ai_v1.test_recipients;
BEGIN
  SELECT * INTO a FROM g2_ai_v1.approvals WHERE approval_id = p_approval_id;
  IF NOT FOUND THEN RETURN 'approval not found'; END IF;
  IF a.revoked_at IS NOT NULL THEN RETURN 'approval revoked: ' || a.revoke_reason; END IF;
  IF a.expires_at <= clock_timestamp() THEN RETURN 'approval expired: approve again'; END IF;
  SELECT * INTO r FROM g2_ai_v1.draft_revisions WHERE revision_id = a.revision_id;
  IF r.workspace_id <> a.workspace_id THEN RETURN 'workspace mismatch'; END IF;
  IF EXISTS (SELECT 1 FROM g2_ai_v1.draft_revisions r2
             WHERE r2.request_id = r.request_id AND r2.revision_no > r.revision_no) THEN
    RETURN 'a newer revision exists: approve the current revision';
  END IF;
  IF r.email_type <> a.email_type OR r.context_hash <> a.context_hash OR r.content_hash <> a.content_hash
     OR r.booking_id IS DISTINCT FROM a.booking_id THEN
    RETURN 'approval does not match the revision (type, context or content)';
  END IF;
  IF g2_ai_v1.content_hash(r.rendered_subject, r.rendered_body) <> a.content_hash THEN
    RETURN 'content hash mismatch';
  END IF;
  IF jsonb_array_length(r.send_blockers) > 0 THEN RETURN 'revision has send blockers'; END IF;
  IF a.delivery_mode = 'team_test_email' THEN
    SELECT * INTO rc FROM g2_ai_v1.test_recipients WHERE recipient_id = a.recipient_id;
    IF NOT FOUND OR NOT rc.active OR rc.address <> a.recipient_address THEN
      RETURN 'recipient not in the active test allowlist';
    END IF;
  END IF;
  IF p_job_id IS NOT NULL THEN
    SELECT * INTO j FROM g2_ai_v1.send_jobs WHERE job_id = p_job_id;
    IF j.approval_id <> a.approval_id OR j.revision_id <> a.revision_id OR j.delivery_mode <> a.delivery_mode
       OR j.recipient_id <> a.recipient_id OR j.recipient_address <> a.recipient_address
       OR j.sender_ref <> a.sender_ref OR j.workspace_id <> a.workspace_id THEN
      RETURN 'send job does not match its approval';
    END IF;
  END IF;
  RETURN NULL;
END $$;

-- An approval is created for a valid revision; afterwards only its revocation may be written.
CREATE OR REPLACE FUNCTION g2_ai_v1.check_approval() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE r g2_ai_v1.draft_revisions;
BEGIN
  IF TG_OP = 'INSERT' THEN
    SELECT * INTO r FROM g2_ai_v1.draft_revisions WHERE revision_id = NEW.revision_id;
    IF NEW.email_type <> r.email_type OR NEW.context_hash <> r.context_hash
       OR NEW.content_hash <> r.content_hash OR NEW.booking_id IS DISTINCT FROM r.booking_id THEN
      RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'Approval does not match the revision';
    END IF;
    IF NEW.revoked_at IS NOT NULL THEN
      RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'A new approval cannot be revoked already';
    END IF;
    RETURN NEW;
  END IF;
  IF OLD.revoked_at IS NOT NULL OR NEW.revoked_at IS NULL
     OR (NEW.approval_id, NEW.workspace_id, NEW.revision_id, NEW.email_type, NEW.booking_id, NEW.context_hash,
         NEW.content_hash, NEW.recipient_id, NEW.recipient_address, NEW.sender_ref, NEW.delivery_mode,
         NEW.reviewer_label, NEW.approved_at, NEW.expires_at)
        IS DISTINCT FROM
        (OLD.approval_id, OLD.workspace_id, OLD.revision_id, OLD.email_type, OLD.booking_id, OLD.context_hash,
         OLD.content_hash, OLD.recipient_id, OLD.recipient_address, OLD.sender_ref, OLD.delivery_mode,
         OLD.reviewer_label, OLD.approved_at, OLD.expires_at) THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'Approval is immutable (only one revocation)';
  END IF;
  RETURN NEW;
END $$;
CREATE OR REPLACE TRIGGER check_approval BEFORE INSERT OR UPDATE ON g2_ai_v1.approvals
  FOR EACH ROW EXECUTE FUNCTION g2_ai_v1.check_approval();

-- Send jobs: identity fixed, legal transitions only, version +1 on every change.
CREATE OR REPLACE FUNCTION g2_ai_v1.check_job() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE a g2_ai_v1.approvals; ok boolean;
BEGIN
  IF TG_OP = 'INSERT' THEN
    SELECT * INTO a FROM g2_ai_v1.approvals WHERE approval_id = NEW.approval_id;
    IF NEW.status <> 'queued' OR NEW.version <> 1 OR NEW.revision_id <> a.revision_id
       OR NEW.delivery_mode <> a.delivery_mode OR NEW.recipient_id <> a.recipient_id
       OR NEW.recipient_address <> a.recipient_address OR NEW.sender_ref <> a.sender_ref THEN
      RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'Send job must start queued and match its approval';
    END IF;
    RETURN NEW;
  END IF;
  IF (NEW.job_id, NEW.workspace_id, NEW.approval_id, NEW.revision_id, NEW.send_key, NEW.delivery_mode,
      NEW.recipient_id, NEW.recipient_address, NEW.sender_ref, NEW.created_at)
     IS DISTINCT FROM (OLD.job_id, OLD.workspace_id, OLD.approval_id, OLD.revision_id, OLD.send_key,
      OLD.delivery_mode, OLD.recipient_id, OLD.recipient_address, OLD.sender_ref, OLD.created_at) THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'Send job identity is immutable';
  END IF;
  IF NEW.status = OLD.status AND NEW.lease_token IS NOT DISTINCT FROM OLD.lease_token THEN
    -- only the tester's receipt note may change without a transition
    IF NEW.version <> OLD.version OR NEW.provider_message_id IS DISTINCT FROM OLD.provider_message_id THEN
      RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'Invalid send job update';
    END IF;
    RETURN NEW;
  END IF;
  ok := (OLD.status, NEW.status) IN (('queued','claimed'), ('queued','failed'), ('claimed','claimed'),
        ('claimed','dispatching'), ('claimed','failed'), ('dispatching','simulated'),
        ('dispatching','provider_accepted'), ('dispatching','failed'), ('dispatching','unknown'),
        ('failed','queued'));
  IF NOT ok THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001',
      MESSAGE = 'Invalid send job transition: ' || OLD.status || ' -> ' || NEW.status;
  END IF;
  IF NEW.version <> OLD.version + 1 THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'Send job version must increase by one';
  END IF;
  RETURN NEW;
END $$;
CREATE OR REPLACE TRIGGER check_job BEFORE INSERT OR UPDATE ON g2_ai_v1.send_jobs
  FOR EACH ROW EXECUTE FUNCTION g2_ai_v1.check_job();

-- ------------------------------------------------------------------ helpers
CREATE OR REPLACE FUNCTION g2_ai_v1.log_event(p_ws text, p_entity text, p_id text, p_kind text,
  p_from text, p_to text, p_actor text, p_detail jsonb) RETURNS void LANGUAGE sql AS $$
  INSERT INTO g2_ai_v1.events (workspace_id, entity, entity_id, kind, from_status, to_status, actor, detail)
  VALUES (p_ws, p_entity, p_id, p_kind, p_from, p_to, p_actor, p_detail)
$$;

-- Generation still 'processing' after its lease -> failed (no automatic second model call);
-- dispatching for more than 5 minutes -> unknown (the email may have left: reconcile, never resend).
CREATE OR REPLACE FUNCTION g2_ai_v1.reconcile_stale(p_workspace_id text) RETURNS integer
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, pg_temp AS $$
DECLARE n integer := 0; rec record;
BEGIN
  FOR rec IN SELECT request_id, workspace_id FROM g2_ai_v1.generation_requests
             WHERE workspace_id = p_workspace_id AND status = 'processing' AND lease_expires_at < clock_timestamp()
             FOR UPDATE SKIP LOCKED LOOP
    UPDATE g2_ai_v1.generation_requests SET status = 'failed', lease_token = NULL, lease_expires_at = NULL,
      error = 'No result stored before the lease expired; not retried automatically: regenerate',
      completed_at = clock_timestamp() WHERE request_id = rec.request_id;
    PERFORM g2_ai_v1.log_event(rec.workspace_id, 'request', rec.request_id::text, 'lease_expired',
                               'processing', 'failed', 'reconcile', NULL);
    n := n + 1;
  END LOOP;
  FOR rec IN SELECT job_id, workspace_id, version FROM g2_ai_v1.send_jobs
             WHERE workspace_id = p_workspace_id AND status = 'dispatching'
               AND dispatch_started_at < clock_timestamp() - interval '5 minutes'
             FOR UPDATE SKIP LOCKED LOOP
    UPDATE g2_ai_v1.send_jobs SET status = 'unknown', lease_token = NULL, lease_expires_at = NULL,
      version = rec.version + 1, updated_at = clock_timestamp(),
      detail = 'No provider result stored within 5 minutes of dispatch: the email may have been sent. '
               'Reconcile with the test inbox; never resend automatically.'
      WHERE job_id = rec.job_id;
    PERFORM g2_ai_v1.log_event(rec.workspace_id, 'job', rec.job_id::text, 'dispatch_unknown',
                               'dispatching', 'unknown', 'reconcile', NULL);
    n := n + 1;
  END LOOP;
  RETURN n;
END $$;

-- ------------------------------------------------------------------ workflow A
CREATE OR REPLACE FUNCTION g2_ai_v1.claim_generation(p_request_id uuid, p_workspace_id text,
  p_engine text DEFAULT 'n8n') RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, pg_temp AS $$
DECLARE r g2_ai_v1.generation_requests; lease uuid := gen_random_uuid();
BEGIN
  SELECT * INTO r FROM g2_ai_v1.generation_requests WHERE request_id = p_request_id FOR UPDATE;
  IF NOT FOUND OR r.workspace_id <> p_workspace_id THEN
    RETURN jsonb_build_object('status', 'not_found', 'request_id', p_request_id);
  END IF;
  IF r.engine <> p_engine THEN
    RETURN jsonb_build_object('status', 'refused', 'request_id', p_request_id,
                              'reason', 'request belongs to engine ' || r.engine);
  END IF;
  IF r.status = 'processing' AND r.lease_expires_at < clock_timestamp() THEN
    UPDATE g2_ai_v1.generation_requests SET status = 'failed', lease_token = NULL, lease_expires_at = NULL,
      error = 'No result stored before the lease expired; not retried automatically: regenerate',
      completed_at = clock_timestamp() WHERE request_id = p_request_id RETURNING * INTO r;
    PERFORM g2_ai_v1.log_event(r.workspace_id, 'request', r.request_id::text, 'lease_expired',
                               'processing', 'failed', p_engine, NULL);
  END IF;
  IF r.status = 'processing' THEN
    RETURN jsonb_build_object('status', 'in_progress', 'request_id', p_request_id);
  END IF;
  IF r.status IN ('succeeded', 'failed') THEN
    RETURN jsonb_build_object('status', r.status, 'request_id', p_request_id, 'result', r.result_json,
                              'errors', r.validation_errors, 'error', r.error, 'analysis_mode', r.analysis_mode);
  END IF;
  UPDATE g2_ai_v1.generation_requests SET status = 'processing', lease_token = lease,
    lease_expires_at = clock_timestamp() + interval '3 minutes', attempts = attempts + 1,
    claimed_at = clock_timestamp() WHERE request_id = p_request_id;
  PERFORM g2_ai_v1.log_event(r.workspace_id, 'request', r.request_id::text, 'claimed', 'queued',
                             'processing', p_engine, NULL);
  RETURN jsonb_build_object('status', 'claimed', 'request_id', p_request_id, 'lease_token', lease,
                            'requested_mode', r.requested_mode, 'context', r.context_json,
                            'context_hash', r.context_hash);
END $$;

-- Store the outcome BEFORE the HTTP response, only by the execution holding the lease.
CREATE OR REPLACE FUNCTION g2_ai_v1.complete_generation(p_request_id uuid, p_lease uuid, p_status text,
  p_result jsonb, p_meta jsonb) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, pg_temp AS $$
DECLARE r g2_ai_v1.generation_requests;
BEGIN
  IF p_status NOT IN ('succeeded', 'failed') THEN
    RETURN jsonb_build_object('stored', false, 'reason', 'status must be succeeded or failed');
  END IF;
  SELECT * INTO r FROM g2_ai_v1.generation_requests WHERE request_id = p_request_id FOR UPDATE;
  IF NOT FOUND OR r.status <> 'processing' OR r.lease_token IS DISTINCT FROM p_lease THEN
    RETURN jsonb_build_object('stored', false, 'reason', 'lease lost: the request was completed or expired');
  END IF;
  IF p_status = 'succeeded' AND (jsonb_typeof(p_result) IS DISTINCT FROM 'object'
                                 OR p_result->>'email_type' IS DISTINCT FROM r.email_type
                                 OR COALESCE(p_meta->>'analysis_mode', '') NOT IN ('live_ai', 'fixture', 'manual')) THEN
    p_status := 'failed';
    p_meta := COALESCE(p_meta, '{}'::jsonb) || jsonb_build_object('error', 'result does not match the request');
  END IF;
  UPDATE g2_ai_v1.generation_requests SET status = p_status, lease_token = NULL, lease_expires_at = NULL,
    result_json = CASE WHEN p_status = 'succeeded' THEN p_result END,
    validation_errors = p_meta->'validation_errors',
    analysis_mode = CASE WHEN p_status = 'succeeded' THEN p_meta->>'analysis_mode' END,
    model = p_meta->>'model', prompt_version = p_meta->>'prompt_version',
    token_usage = p_meta->'token_usage', error = left(p_meta->>'error', 1000),
    completed_at = clock_timestamp()
  WHERE request_id = p_request_id RETURNING * INTO r;
  PERFORM g2_ai_v1.log_event(r.workspace_id, 'request', r.request_id::text, 'completed', 'processing',
                             p_status, r.engine, jsonb_build_object('analysis_mode', r.analysis_mode));
  RETURN jsonb_build_object('stored', true, 'request_id', p_request_id, 'status', r.status,
                            'result', r.result_json, 'errors', r.validation_errors, 'error', r.error,
                            'analysis_mode', r.analysis_mode);
END $$;

-- ------------------------------------------------------------------ workflow B
-- Atomic claim: approval re-checked and job moved queued -> claimed in ONE transaction.
CREATE OR REPLACE FUNCTION g2_ai_v1.claim_send_job(p_job_id uuid, p_workspace_id text, p_executor text,
  p_sender_ref text) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, pg_temp AS $$
DECLARE j g2_ai_v1.send_jobs; a_id bigint; problem text; lease uuid := gen_random_uuid();
BEGIN
  PERFORM g2_ai_v1.reconcile_stale(p_workspace_id);
  SELECT approval_id INTO a_id FROM g2_ai_v1.send_jobs WHERE job_id = p_job_id AND workspace_id = p_workspace_id;
  IF NOT FOUND THEN
    RETURN jsonb_build_object('status', 'refused', 'job_id', p_job_id, 'reason', 'send job not found');
  END IF;
  PERFORM 1 FROM g2_ai_v1.approvals WHERE approval_id = a_id FOR UPDATE;   -- lock order: approval, job
  SELECT * INTO j FROM g2_ai_v1.send_jobs WHERE job_id = p_job_id FOR UPDATE;
  IF j.status IN ('simulated', 'provider_accepted', 'failed', 'unknown') THEN
    RETURN jsonb_build_object('status', 'already', 'job_id', p_job_id, 'job_status', j.status,
                              'provider_message_id', j.provider_message_id, 'detail', j.detail);
  END IF;
  IF j.status = 'dispatching' OR (j.status = 'claimed' AND j.lease_expires_at > clock_timestamp()) THEN
    RETURN jsonb_build_object('status', 'in_progress', 'job_id', p_job_id, 'job_status', j.status);
  END IF;
  problem := g2_ai_v1.approval_problem(a_id, p_job_id);
  IF problem IS NULL AND j.delivery_mode = 'team_test_email' AND j.sender_ref IS DISTINCT FROM p_sender_ref THEN
    problem := 'sender changed (workflow sender ' || COALESCE(p_sender_ref, 'none') || '): approve again';
  END IF;
  IF problem IS NOT NULL THEN
    UPDATE g2_ai_v1.send_jobs SET status = 'failed', lease_token = NULL, lease_expires_at = NULL,
      version = j.version + 1, detail = 'Not sent: ' || problem, updated_at = clock_timestamp(),
      finished_at = clock_timestamp(), executor = p_executor WHERE job_id = p_job_id;
    PERFORM g2_ai_v1.log_event(j.workspace_id, 'job', p_job_id::text, 'refused_at_claim', j.status, 'failed',
                               p_executor, jsonb_build_object('reason', problem));
    RETURN jsonb_build_object('status', 'refused', 'job_id', p_job_id, 'reason', problem);
  END IF;
  UPDATE g2_ai_v1.send_jobs SET status = 'claimed', lease_token = lease,
    lease_expires_at = clock_timestamp() + interval '2 minutes', version = j.version + 1,
    executor = p_executor, updated_at = clock_timestamp() WHERE job_id = p_job_id;
  PERFORM g2_ai_v1.log_event(j.workspace_id, 'job', p_job_id::text, 'claimed', j.status, 'claimed', p_executor, NULL);
  RETURN jsonb_build_object('status', 'claimed', 'job_id', p_job_id, 'lease_token', lease,
                            'version', j.version + 1, 'delivery_mode', j.delivery_mode);
END $$;

-- claimed -> dispatching with the right lease, approval re-checked; returns the approved email
-- read from the database (never from the webhook payload). Committed before the provider call.
CREATE OR REPLACE FUNCTION g2_ai_v1.begin_dispatch(p_job_id uuid, p_lease uuid) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, pg_temp AS $$
DECLARE j g2_ai_v1.send_jobs; a_id bigint; problem text; r g2_ai_v1.draft_revisions;
BEGIN
  SELECT approval_id INTO a_id FROM g2_ai_v1.send_jobs WHERE job_id = p_job_id;
  IF NOT FOUND THEN RETURN jsonb_build_object('ok', false, 'reason', 'send job not found'); END IF;
  PERFORM 1 FROM g2_ai_v1.approvals WHERE approval_id = a_id FOR UPDATE;
  SELECT * INTO j FROM g2_ai_v1.send_jobs WHERE job_id = p_job_id FOR UPDATE;
  IF j.status <> 'claimed' OR j.lease_token IS DISTINCT FROM p_lease OR j.lease_expires_at <= clock_timestamp() THEN
    RETURN jsonb_build_object('ok', false, 'reason', 'lease lost: another execution owns this job or it expired',
                              'job_status', j.status);
  END IF;
  problem := g2_ai_v1.approval_problem(a_id, p_job_id);
  IF problem IS NOT NULL THEN
    UPDATE g2_ai_v1.send_jobs SET status = 'failed', lease_token = NULL, lease_expires_at = NULL,
      version = j.version + 1, detail = 'Not sent: ' || problem, updated_at = clock_timestamp(),
      finished_at = clock_timestamp() WHERE job_id = p_job_id;
    PERFORM g2_ai_v1.log_event(j.workspace_id, 'job', p_job_id::text, 'refused_before_dispatch', 'claimed',
                               'failed', j.executor, jsonb_build_object('reason', problem));
    RETURN jsonb_build_object('ok', false, 'reason', problem, 'job_status', 'failed');
  END IF;
  SELECT * INTO r FROM g2_ai_v1.draft_revisions WHERE revision_id = j.revision_id;
  UPDATE g2_ai_v1.send_jobs SET status = 'dispatching', version = j.version + 1,
    dispatch_started_at = clock_timestamp(), updated_at = clock_timestamp() WHERE job_id = p_job_id;
  PERFORM g2_ai_v1.log_event(j.workspace_id, 'job', p_job_id::text, 'dispatching', 'claimed', 'dispatching',
                             j.executor, NULL);
  RETURN jsonb_build_object('ok', true, 'job_id', p_job_id, 'delivery_mode', j.delivery_mode,
                            'to', j.recipient_address, 'subject', r.rendered_subject, 'body', r.rendered_body,
                            'content_hash', r.content_hash, 'version', j.version + 1);
END $$;

-- Provider result, stored before the HTTP response. Only the lease holder of a dispatching job.
CREATE OR REPLACE FUNCTION g2_ai_v1.finish_dispatch(p_job_id uuid, p_lease uuid, p_outcome text,
  p_provider_message_id text, p_detail text) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, pg_temp AS $$
DECLARE j g2_ai_v1.send_jobs;
BEGIN
  SELECT * INTO j FROM g2_ai_v1.send_jobs WHERE job_id = p_job_id FOR UPDATE;
  IF NOT FOUND OR j.status <> 'dispatching' OR j.lease_token IS DISTINCT FROM p_lease THEN
    RETURN jsonb_build_object('stored', false, 'reason', 'not the dispatching lease holder',
                              'job_status', j.status);
  END IF;
  IF p_outcome NOT IN ('simulated', 'provider_accepted', 'failed', 'unknown')
     OR (p_outcome = 'simulated' AND j.delivery_mode <> 'mock')
     OR (p_outcome = 'provider_accepted' AND j.delivery_mode <> 'team_test_email') THEN
    p_detail := 'Invalid outcome ' || COALESCE(p_outcome, 'null') || ' recorded as unknown. ' || COALESCE(p_detail, '');
    p_outcome := 'unknown';
  END IF;
  UPDATE g2_ai_v1.send_jobs SET status = p_outcome, lease_token = NULL, lease_expires_at = NULL,
    version = j.version + 1, provider_message_id = left(p_provider_message_id, 200), detail = left(p_detail, 1000),
    updated_at = clock_timestamp(), finished_at = clock_timestamp() WHERE job_id = p_job_id
  RETURNING * INTO j;
  PERFORM g2_ai_v1.log_event(j.workspace_id, 'job', p_job_id::text, 'dispatched', 'dispatching', p_outcome,
                             j.executor, jsonb_build_object('provider_message_id', j.provider_message_id));
  RETURN jsonb_build_object('stored', true, 'job_id', p_job_id, 'job_status', j.status,
                            'provider_message_id', j.provider_message_id, 'detail', j.detail);
END $$;
