class Row(dict):
    """Row usable like sqlite3.Row: by column name, by position and as dict(row)."""

    def __getitem__(self, key):
        if isinstance(key, int):
            return list(self.values())[key]
        return super().__getitem__(key)

    def __iter__(self):  # like sqlite3.Row: iterating gives values (dict(rows) of pairs works)
        return iter(list(self.values()))


def _row_factory(cursor):
    names = [d.name for d in cursor.description] if cursor.description else []
    return lambda values: Row(zip(names, values))


class _Cursor:
    def __init__(self, cur, lastrowid=None):
        self._cur, self.lastrowid, self.rowcount = cur, lastrowid, cur.rowcount
        self._buffer = None

    def fetchone(self):
        if self._buffer is not None:
            return self._buffer.pop(0) if self._buffer else None
        return self._cur.fetchone() if self._cur.description else None

    def fetchall(self):
        if self._buffer is not None:
            rows, self._buffer = self._buffer, []
            return rows
        return self._cur.fetchall() if self._cur.description else []


def _translate(sql: str) -> str:
    return sql.replace('%', '%%').replace('?', '%s')


def _integrity(exc) -> sqlite3.IntegrityError:
    """psycopg refusal -> sqlite3.IntegrityError with the SQLite wording."""
    from psycopg import errors as e
    d = exc.diag
    if isinstance(exc, e.CheckViolation):
        return sqlite3.IntegrityError(f'CHECK constraint failed: {d.constraint_name}')
    if isinstance(exc, e.UniqueViolation):
        return sqlite3.IntegrityError(f'UNIQUE constraint failed: {d.constraint_name}')
    if isinstance(exc, e.ForeignKeyViolation):
        return sqlite3.IntegrityError('FOREIGN KEY constraint failed')
    if isinstance(exc, e.NotNullViolation):
        return sqlite3.IntegrityError(f'NOT NULL constraint failed: {d.column_name}')
    return sqlite3.IntegrityError(d.message_primary or str(exc))


class PgConnection:
    """The subset of the sqlite3.Connection API used by the G2 service."""
    backend = 'postgresql'

    def __init__(self, dsn: str, schema: str):
        import psycopg
        self._psycopg = psycopg
        self.schema = schema
        # prepare_threshold=None: no server-side prepared statements (safe behind a pooler).
        self._con = psycopg.connect(dsn, row_factory=_row_factory, autocommit=True, prepare_threshold=None)
        # CREATE SCHEMA only when missing, so a runtime role without CREATE on the database can open
        # a store that a bootstrap / owner role created. search_path is per SESSION: use a direct
        # connection or a session pooler, not a transaction pooler (README_DEPLOY_CLOUD.md).
        if self._con.execute('SELECT 1 FROM pg_namespace WHERE nspname = %s', (schema,)).fetchone() is None:
            self._con.execute(f'CREATE SCHEMA IF NOT EXISTS "{schema}"')
        self._con.execute(f'SET search_path TO "{schema}"')
        self._con.execute(f"SET lock_timeout = '{LOCK_TIMEOUT}'")

    def in_transaction(self) -> bool:
        from psycopg.pq import TransactionStatus
        return self._con.info.transaction_status != TransactionStatus.IDLE

    def begin(self) -> None:
        """Open a transaction unless one is open already (it is then joined)."""
        if not self.in_transaction():
            self._con.execute('BEGIN')

    def tables(self) -> set[str]:
        rows = self._con.execute("""SELECT table_name FROM information_schema.tables
                                    WHERE table_schema = current_schema()""").fetchall()
        return {r['table_name'] for r in rows}

    def executescript(self, script: str) -> None:
        self._con.execute(script)  # several statements: one implicit transaction
        self.commit()

    def execute(self, sql: str, params=()):
        e = self._psycopg.errors
        query = _translate(sql)
        if re.match(r'\s*(SAVEPOINT|RELEASE|ROLLBACK|BEGIN|COMMIT)\b', query, re.I):
            # Caller-managed transaction control runs as is (never inside our own savepoint);
            # a savepoint needs a transaction, as SQLite opens one implicitly.
            if re.match(r'\s*SAVEPOINT\b', query, re.I):
                self.begin()
            return _Cursor(self._con.execute(query, tuple(params)))
        m = re.match(r'\s*INSERT\s+INTO\s+(\w+)', query, re.I)
        returning = m and m.group(1) in PK and 'RETURNING' not in query.upper()
        if returning:
            query = query.rstrip().rstrip(';') + f' RETURNING {PK[m.group(1)]}'
        inside = self.in_transaction()
        if inside:
            self._con.execute('SAVEPOINT g2_stmt')
        try:
            cur = self._con.execute(query, tuple(params))
        except Exception as exc:
            if inside:
                self._con.execute('ROLLBACK TO SAVEPOINT g2_stmt')
            if isinstance(exc, (e.IntegrityError, e.RaiseException)):
                raise _integrity(exc) from None
            if isinstance(exc, e.LockNotAvailable):
                raise sqlite3.OperationalError('database is locked (another session is writing; '
                                               'try again)') from None
            raise
        if inside:
            self._con.execute('RELEASE SAVEPOINT g2_stmt')
        if returning:
            rows = cur.fetchall()
            out = _Cursor(cur, rows[0][0] if rows else None)
            out._buffer = []
            return out
        return _Cursor(cur)

    def commit(self):
        if self.in_transaction():
            self._con.execute('COMMIT')

    def rollback(self):
        if self.in_transaction():
            self._con.execute('ROLLBACK')

    def close(self):
        self._con.close()


def parse_target(target: str) -> tuple[str, str]:
    """'postgresql://...#schema' -> (dsn, schema)."""
    dsn, _, schema = str(target).partition('#')
    schema = schema or 'g2_state'
    if not SCHEMA_NAME.match(schema):
        raise ValueError(f'Invalid PostgreSQL schema name for the G2 store: {schema!r}')
    return dsn, schema


def is_pg(target) -> bool:
    return str(target).startswith(('postgresql://', 'postgres://'))


def connect(target: str) -> PgConnection:
    dsn, schema = parse_target(target)
    return PgConnection(dsn, schema)


